IF SCHEMA_ID('geo') IS NULL EXEC('CREATE SCHEMA geo');
IF OBJECT_ID('geo.GeoCache','U') IS NULL
CREATE TABLE geo.GeoCache(
 Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY, QueryKey NVARCHAR(450) NOT NULL UNIQUE, ResultJson NVARCHAR(MAX) NOT NULL,
 ExpiresAt DATETIME2 NOT NULL, IsFailure BIT NOT NULL DEFAULT 0,
 CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), UpdatedAt DATETIME2 NULL);
