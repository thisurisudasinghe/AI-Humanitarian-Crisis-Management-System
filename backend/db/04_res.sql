-- Member 4 / M5 Resources. Run after 00_foundation.sql.
IF SCHEMA_ID('res') IS NULL EXEC('CREATE SCHEMA res');
IF OBJECT_ID('res.ResourceTypes','U') IS NULL
CREATE TABLE res.ResourceTypes(
 Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY, Name NVARCHAR(120) NOT NULL, Unit NVARCHAR(40) NOT NULL,
 Description NVARCHAR(500) NULL, CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), UpdatedAt DATETIME2 NULL);
IF OBJECT_ID('res.Inventories','U') IS NULL
CREATE TABLE res.Inventories(
 Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY, ResourceTypeId UNIQUEIDENTIFIER NOT NULL, OrgId UNIQUEIDENTIFIER NOT NULL,
 Quantity DECIMAL(18,2) NOT NULL, Available DECIMAL(18,2) NOT NULL, Reserved DECIMAL(18,2) NOT NULL DEFAULT 0,
 Allocated DECIMAL(18,2) NOT NULL DEFAULT 0, Dispatched DECIMAL(18,2) NOT NULL DEFAULT 0, Utilised DECIMAL(18,2) NOT NULL DEFAULT 0,
 ReorderThreshold DECIMAL(18,2) NOT NULL DEFAULT 0, ExpiryDate DATETIME2 NULL, Lat FLOAT NULL, Lng FLOAT NULL,
 AccessibilityCapable BIT NOT NULL DEFAULT 0, CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), UpdatedAt DATETIME2 NULL,
 CONSTRAINT CK_Inventories_NonNegative CHECK(Available>=0 AND Reserved>=0 AND Allocated>=0 AND Dispatched>=0 AND Utilised>=0));
IF OBJECT_ID('res.Allocations','U') IS NULL
CREATE TABLE res.Allocations(
 Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY, RequestId UNIQUEIDENTIFIER NOT NULL, InventoryId UNIQUEIDENTIFIER NOT NULL,
 Quantity DECIMAL(18,2) NOT NULL, DecisionId UNIQUEIDENTIFIER NOT NULL, Status NVARCHAR(30) NOT NULL,
 Explanation NVARCHAR(1000) NOT NULL, IdempotencyKey NVARCHAR(200) NOT NULL UNIQUE,
 CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), UpdatedAt DATETIME2 NULL);
IF OBJECT_ID('res.Dispatches','U') IS NULL
CREATE TABLE res.Dispatches(
 Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY, AllocationId UNIQUEIDENTIFIER NOT NULL, Quantity DECIMAL(18,2) NOT NULL,
 ConfirmedAt DATETIME2 NULL, ConfirmedBy UNIQUEIDENTIFIER NULL, Status NVARCHAR(30) NOT NULL,
 CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), UpdatedAt DATETIME2 NULL);
IF OBJECT_ID('res.AssistanceRequests','U') IS NULL
CREATE TABLE res.AssistanceRequests(
 Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY, FromOrgId UNIQUEIDENTIFIER NOT NULL, ToOrgId UNIQUEIDENTIFIER NULL,
 ResourceTypeId UNIQUEIDENTIFIER NOT NULL, Quantity DECIMAL(18,2) NOT NULL, Reason NVARCHAR(1000) NOT NULL,
 Status NVARCHAR(20) NOT NULL, ShelterId UNIQUEIDENTIFIER NULL, ResponseReason NVARCHAR(1000) NULL,
 CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), UpdatedAt DATETIME2 NULL);

-- Member 4 query indexes (safe to re-run).
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name='IX_Inventories_OrgId' AND object_id=OBJECT_ID('res.Inventories'))
 CREATE INDEX IX_Inventories_OrgId ON res.Inventories(OrgId);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name='IX_Inventories_ResourceTypeId' AND object_id=OBJECT_ID('res.Inventories'))
 CREATE INDEX IX_Inventories_ResourceTypeId ON res.Inventories(ResourceTypeId);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name='IX_Allocations_RequestId' AND object_id=OBJECT_ID('res.Allocations'))
 CREATE INDEX IX_Allocations_RequestId ON res.Allocations(RequestId);
