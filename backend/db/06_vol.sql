-- Member 4 / M7 Volunteers.
IF SCHEMA_ID('vol') IS NULL EXEC('CREATE SCHEMA vol');
IF OBJECT_ID('vol.Volunteers','U') IS NULL
CREATE TABLE vol.Volunteers(
 Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY, UserId UNIQUEIDENTIFIER NOT NULL UNIQUE, SkillsJson NVARCHAR(MAX) NOT NULL DEFAULT '[]',
 LanguagesJson NVARCHAR(MAX) NOT NULL DEFAULT '[]', VerificationStatus NVARCHAR(20) NOT NULL DEFAULT 'Pending',
 Active BIT NOT NULL DEFAULT 1, Lat FLOAT NULL, Lng FLOAT NULL, CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), UpdatedAt DATETIME2 NULL);
IF OBJECT_ID('vol.Availability','U') IS NULL
CREATE TABLE vol.Availability(
 Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY, VolunteerId UNIQUEIDENTIFIER NOT NULL, StartsAt DATETIME2 NOT NULL, EndsAt DATETIME2 NOT NULL,
 CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), UpdatedAt DATETIME2 NULL, CONSTRAINT CK_VolAvailability CHECK(EndsAt>StartsAt));
IF OBJECT_ID('vol.Tasks','U') IS NULL
CREATE TABLE vol.Tasks(
 Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY, RequestId UNIQUEIDENTIFIER NULL, Title NVARCHAR(160) NOT NULL, RequiredSkillsJson NVARCHAR(MAX) NOT NULL DEFAULT '[]',
 Lat FLOAT NULL, Lng FLOAT NULL, ScheduledAt DATETIME2 NULL, Status NVARCHAR(20) NOT NULL DEFAULT 'Open',
 VolunteerId UNIQUEIDENTIFIER NULL, CompletedAt DATETIME2 NULL, CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), UpdatedAt DATETIME2 NULL);
IF OBJECT_ID('vol.Activities','U') IS NULL
CREATE TABLE vol.Activities(
 Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY, VolunteerId UNIQUEIDENTIFIER NOT NULL, TaskId UNIQUEIDENTIFIER NOT NULL,
 CompletedBy UNIQUEIDENTIFIER NOT NULL, CompletedAt DATETIME2 NOT NULL, CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), UpdatedAt DATETIME2 NULL);
